def redes_neuronales(x,y):
  'X es la entrada de valores que quieres usar como referencia para predecir los valores y, necesitan estar definidas las columnas por pandas'
  import tensorflow
  from tensorflow import keras
  from tensorflow.keras import layers
  import pandas as pd
  import numpy as np
  import matplotlib.pyplot as plt
  from sklearn.model_selection import train_test_split
  from sklearn.preprocessing import StandardScaler
  from tensorflow.keras import regularizers
  from tensorflow.keras.callbacks import EarlyStopping
  x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.45, random_state=42)
  model = keras.Sequential([layers.Dense(512, activation="relu"),
                              layers.Dense(100, activation="relu"),
                              layers.Dense(100, activation="relu"),
                              layers.Dense(100, activation="relu"),
                              layers.Dense(1, activation="sigmoid")])
  model.compile(optimizer="rmsprop",
                  loss="binary_crossentropy",
                  metrics=["accuracy"])

  history = model.fit(x_train, y_train, epochs=500, batch_size=100)
  model.summary()
  hist_df = pd.DataFrame(history.history)

  plt.figure(figsize=(7,5))

  plt.plot(hist_df["accuracy"], label="Precisión", color="green", linewidth=0.9)
  plt.plot(hist_df["loss"], label="Pérdida", color="black", linewidth=0.9)

  plt.xlabel("Épocas")
  plt.ylabel("Valor")
  plt.title("Entrenamiento\n")
  plt.legend()
  plt.grid(True)
  plt.ylim(0,1)
  plt.show()
  model.evaluate(x_test,y_test)

