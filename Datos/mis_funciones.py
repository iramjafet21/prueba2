def curva_roc(y_true, y_predo, titulo, rep, fold, output_dir='.'):
  'En este metodo se hace la curva roc de dos valores, y_true y y_pred los cuales, y_true, y titulo es la columna a analizar'
  import matplotlib.pyplot as plt
  from sklearn.metrics import roc_curve, roc_auc_score
  # Calcular FPR, TPR y thresholds
  fpr, tpr, thresholds = roc_curve(y_true, y_predo)

  # Calcular AUC
  auc = roc_auc_score(y_true, y_predo)

  # Graficar curva ROC
  plt.figure(figsize=(6, 5)) # Added figure size for consistency
  plt.plot(fpr, tpr, label=f"AUC = {auc:.2f}", color="green")
  plt.plot([0, 1], [0, 1], linestyle="--", color="gray")  # línea aleatoria
  plt.xlabel("Tasa de Falsos Positivos (FPR)")
  plt.ylabel("Tasa de Verdaderos Positivos (TPR)")
  plt.title(f"Curva ROC de {titulo} - Rep {rep+1}, Fold {fold+1}\n")
  plt.legend()
  plt.savefig(f"{output_dir}/curva_roc_{titulo}_rep{rep+1}_fold{fold+1}.png")
  plt.close() # Close the plot to free up memory

