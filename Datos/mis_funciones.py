def metodo_tsne(archivo, columna_analizar, columna_color, rep, fold, output_dir='.'):
    """
    Genera visualización t-SNE y exporta tanto en HTML interactivo como en PNG con estilo Plotly.
    """
    import numpy as np
    import plotly.express as px
    from sklearn.manifold import TSNE

    # Configuración de reproducibilidad
    np.random.seed(42)

    # Ajustar t-SNE (limitando a 100 filas como en tu versión original)
    tsne = TSNE(perplexity=20, early_exaggeration=50, learning_rate=350, random_state=42)
    X_valid_2D = tsne.fit_transform(archivo[0:100])

    # Normalización de valores a escala [0, 1]
    X_valid_2D = (X_valid_2D - X_valid_2D.min()) / (X_valid_2D.max() - X_valid_2D.min())

    # Crear gráfico interactivo con Plotly
    fig = px.scatter(
        x=X_valid_2D[:, 0],
        y=X_valid_2D[:, 1],
        color=columna_analizar.astype(str),
        title=f"Visualización del conjunto de datos reales de {columna_color}\n- Rep {rep+1}, Fold {fold+1}"
    )

    fig.update_traces(marker=dict(size=10, opacity=0.7, line=dict(width=2)))
    fig.update_layout(showlegend=True)

    # Guardar en HTML interactivo
    fig.write_html(f"{output_dir}/tsne_real_{columna_color}_rep{rep+1}_fold{fold+1}.html")

    # Guardar en PNG con estilo Plotly (requiere kaleido)
    fig.write_image(
        f"{output_dir}/tsne_real_{columna_color}_rep{rep+1}_fold{fold+1}.png",
        width=1200, height=800, scale=2  # puedes ajustar tamaño y resolución
    )

